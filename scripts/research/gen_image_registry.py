"""Builds src/data/product-images.official.ts from images_official.json (validated downloads)."""
import json, sys
BRAND = {"canyon": "Canyon", "cervelo": "Cervélo", "santa-cruz": "Santa Cruz", "specialized": "Specialized", "tern": "Tern"}
recs = {r["id"]: r for r in json.load(open("official.json"))["records"]}
rejected = set(json.load(open("image_review.json")).get("rejected", [])) if len(sys.argv) > 1 else set()
out = []
for e in json.load(open("images_official.json")):
    if e["status"] != "ok" or e["subjectId"] in rejected or e["subjectId"] not in recs: continue
    r = recs[e["subjectId"]]; b = BRAND[e["brand"]]
    out.append({
        "id": f"img-{e['subjectId']}", "subjectKind": "bike", "subjectId": e["subjectId"],
        "primary_image_url": e["file"], "width": e["width"], "height": e["height"],
        "alt": f"{b} {r['name']} — official product photo",
        "image_source_url": e["page"], "original_file_url": e["originalUrl"],
        "image_source_type": "manufacturer", "image_license_status": "manufacturer-product-image",
        "license": f"© {b}", "licenseUrl": None, "author": b,
        "image_verification_status": "verified", "image_model_match": "exact",
        "matchNotes": f"Image declared for this exact product by {b}'s own product page ({e['how']}). Downloaded 2026-11-16: HTTP 200, {e['contentType']}, {e['origWidth']}×{e['origHeight']} px; visually checked on a review contact sheet; no other record uses the same source file.",
        "view": "product", "last_image_verified_at": "2026-11-16", "sha256": e["sha256"],
    })
ts = 'import type { ProductImage } from "@/lib/types";\n\n/**\n * GENERATED by scripts/research/gen_image_registry.py — official manufacturer product photos.\n * Each image is the one the manufacturer declares for that exact product on its own product page;\n * downloaded, validated (status, type, decode, size), de-duplicated by checksum and reviewed visually.\n */\nexport const OFFICIAL_PRODUCT_IMAGES: ProductImage[] = ' + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
open("../../src/data/product-images.official.ts", "w").write(ts)
print(len(out), "official images registered;", len(rejected), "rejected after review")
